export function defaultNumbers(size, name) {
  if (NUMBERS[name]) return NUMBERS[name].slice();
  return Array.from({ length: size }, (_, i) => i + 1);
}

// Mirror a formation for the team attacking left.
export function mirror(pts) {
  return pts.map(([x, y]) => [1 - x, 1 - y]);
}
